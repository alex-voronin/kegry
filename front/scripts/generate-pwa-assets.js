const fs = require('fs');
const path = require('path');

const PUBLIC_DIR = path.join(process.cwd(), 'public');
const ASSETS_DIR = path.join(PUBLIC_DIR, 'assets');
const ICONS_DIR = path.join(PUBLIC_DIR, 'icons');
const OUTPUT_FILE = path.join(PUBLIC_DIR, 'pwa-assets.js');

function getAllFiles(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;

  const files = fs.readdirSync(dir);

  files.forEach((file) => {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      getAllFiles(filePath, fileList);
    } else {
      // Ignore hidden files and the output file itself
      // Also exclude landing assets
      if (
        !file.startsWith('.') &&
        filePath !== OUTPUT_FILE &&
        !file.endsWith('.js') &&
        !file.endsWith('.json') &&
        !filePath.includes('/assets/landing/')
      ) {
        fileList.push(filePath);
      }
    }
  });

  return fileList;
}

console.log('Generating PWA asset list...');

const assetFiles = getAllFiles(ASSETS_DIR);
const iconFiles = getAllFiles(ICONS_DIR);

const allFiles = [...assetFiles, ...iconFiles];

// Convert to relative URLs
const urls = allFiles.map((file) => {
  return file.replace(PUBLIC_DIR, '').replace(/\\/g, '/');
});

// urls.push('/');
urls.push('/manifest.json');

// Sort for determinism
urls.sort();

const content = `// Auto-generated by scripts/generate-pwa-assets.js
const STATIC_ASSETS = ${JSON.stringify(urls, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, content);

console.log(`Generated ${urls.length} assets in ${OUTPUT_FILE}`);
